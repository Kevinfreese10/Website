/**
 * Data model for the AI order agent (AI-ORDER-AGENT-PLAN.md §6.8).
 * Firestore collections: agentProposals, agentRuns, autonomyPolicy.
 */

import type { RuleOutcome } from '@/lib/verification/rules';
import type { ExtractedDocumentFacts } from '@/lib/verification/facts';

export type AgentTrigger = 'upload' | 'questionnaire' | 'payment' | 'cron' | 'manual';

export type ProposalKind =
  | 'client_message'   // post a note to Communication History (optionally email)
  | 'document_review'  // approve / reject an upload
  | 'handoff'          // a step Kevin/staff must do by hand; approving marks it done
  | 'document_draft'   // drafts generated by the DOCUMENT adapter; approving signs (Kevin docs) and posts to the client
  | 'email_submission' // EMAIL adapter: send a pack (or a follow-up) to a regulator; approving sends it
  | 'portal_stage'     // PORTAL adapter: approving queues a browser job that fills the portal and stops before submit
  | 'portal_submit'    // PORTAL adapter: the job is staged; approving presses submit (screenshots attached)
  | 'otp'              // PORTAL adapter: the portal asked for a one-time PIN; approving with the code resumes the job
  | 'status_change';   // move client-visible status (never to Completed/Cancelled/Pending Payment)

export type ProposalStatus = 'pending' | 'approved' | 'edited' | 'rejected' | 'expired';

export type ClientMessagePayload = {
  text: string;
  /** Also send the templated document-request email. */
  sendEmail?: boolean;
  /** Set the client-visible status after posting (only 'Waiting on Customer' | 'Processing' | 'Under Review' allowed). */
  setStatus?: 'Waiting on Customer' | 'Processing' | 'Under Review' | 'Waiting for Information';
  purpose: 'chase' | 'acknowledge' | 'reject_document' | 'deliver' | 'query' | 'other';
};

export type DocumentReviewPayload = {
  uploadId: string;
  requirementLabel: string;
  decision: 'approved' | 'rejected';
  reason?: string;
  /** Message to the client when rejecting. */
  clientMessage?: string;
};

export type HandoffPayload = {
  stepId: string;
  stepTitle: string;
  stepType: string;
  instructions?: string;
  /** Prepared values / links for the human doing the step. */
  sheet: { label: string; value: string }[];
};

export type DocumentDraftPayload = {
  stepId: string;
  stepTitle: string;
  drafts: { draftId: string; templateId: string; title: string; fileName: string; fileUrl: string; warnings: string[]; signature: string }[];
  /** Templates that could not be drafted and why. */
  failed: { templateId: string; missing: string[]; error?: string }[];
  /** Post the approved (signed) files to Communication History for the client. */
  postToClient: boolean;
  clientMessage?: string;
};

export type EmailSubmissionPayload = {
  stepId: string;
  stepTitle: string;
  purpose: 'submission' | 'follow_up';
  to: string;
  cc?: string;
  subject: string;
  /** Plain text body; converted to simple HTML on send. */
  body: string;
  attachments: { name: string; url: string; source: 'draft' | 'upload' }[];
  /** Tag embedded in the subject so replies can be matched: [MYACC-<orderNumber>] */
  tag: string;
  /** For follow-ups: which submission this chases. */
  submissionId?: string;
  /** ⚠ address unverified in the playbook — shown loudly in the inbox. */
  addressUnverified?: boolean;
};

export type PortalStagePayload = {
  stepId: string;
  stepTitle: string;
  portalId: string;
  procedure: string;
  /** Field values the driver will type. Shown to Kevin before queuing. */
  input: Record<string, any>;
  /** Encrypted credential blobs (never decrypted in the app). */
  credentials: { label: string; encryptedValue: string }[];
  submitMode: 'stage' | 'auto';
};

export type PortalSubmitPayload = {
  stepId: string;
  stepTitle: string;
  jobId: string;
  portalId: string;
  procedure: string;
  screenshots: { label: string; url: string }[];
  /** What the driver reports it filled, for review. */
  reviewSheet: { label: string; value: string }[];
};

export type OtpPayload = {
  stepId: string;
  jobId: string;
  portalId: string;
  /** Where the portal said it sent the code, if known. */
  sentTo?: string;
  requestedAt: string;
  expiresAt: string;
  /** Filled by Kevin on approval (via editedPayload). */
  code?: string;
};

export type StatusChangePayload = {
  to: 'Waiting on Customer' | 'Processing' | 'Under Review' | 'Waiting for Information';
  reason: string;
};

export type AgentProposal = {
  id: string;
  orderId: string;
  orderNumber: string;           // originalOrderId || id, for display
  serviceId: string;
  serviceTitle: string;
  stepId?: string;
  kind: ProposalKind;
  title: string;                 // one line for the queue
  summary: string;               // 1–3 sentences: why the agent proposes this
  payload: ClientMessagePayload | DocumentReviewPayload | HandoffPayload | DocumentDraftPayload | EmailSubmissionPayload | PortalStagePayload | PortalSubmitPayload | OtpPayload | StatusChangePayload;
  evidence: {
    entity?: Record<string, any>;
    ruleOutcome?: RuleOutcome;
    facts?: ExtractedDocumentFacts;
    mechanical?: any;
    missing?: string[];
    notes?: string[];
  };
  /** Higher = more urgent. Computed at creation, recomputed when listing. */
  priority: number;
  status: ProposalStatus;
  createdAt: string;
  runId: string;
  /** Prevents duplicate proposals for the same thing while one is pending. */
  dedupeKey: string;
  decidedAt?: string;
  decidedBy?: string;
  decidedByName?: string;
  decisionNote?: string;
  /** Payload as edited by Kevin, when status === 'edited'. */
  editedPayload?: AgentProposal['payload'];
  executionResult?: { ok: boolean; message: string };
};

export type AgentRun = {
  id: string;
  orderId: string;
  trigger: AgentTrigger;
  startedAt: string;
  finishedAt?: string;
  ok: boolean;
  error?: string;
  reads: string[];
  writes: string[];
  proposalsCreated: string[];
  modelCalls: number;
  notes: string[];
};

export type AutonomyPolicy = {
  serviceId: string;
  /** keyed by ProposalKind (+ ':' + purpose for client messages) */
  actions: Record<string, {
    level: 'propose' | 'auto';
    consecutiveAccepts: number;
    totalAccepts: number;
    totalEdits: number;
    totalRejects: number;
    promotedAt?: string;
    promotedBy?: string;
    demotedAt?: string;
    demotedReason?: string;
  }>;
  updatedAt: string;
};

export const PROMOTION_THRESHOLD = 50;

/** Statuses the agent will ever set on the client-visible `status`. Completed/Cancelled/Pending Payment are never here. */
export const AGENT_ALLOWED_STATUSES = ['Waiting on Customer', 'Processing', 'Under Review', 'Waiting for Information'] as const;

/** A regulator submission recorded on orders/{id}.regulatorSubmissions[] (plan §6.5). */
export type RegulatorSubmission = {
  id: string;
  stepId: string;
  serviceId: string;
  to: string;
  subject: string;
  tag: string;
  sentAt: string;
  sentBy: string;
  attachmentNames: string[];
  status: 'sent' | 'acknowledged' | 'queried' | 'closed';
  followUpsSent: string[];         // ISO dates
  replies: { mailId: string; from: string; subject: string; receivedAt: string; snippet: string }[];
  reference?: string;              // regulator reference number once known
};

/** Inbound mail from the submissions mailbox (regulatorMail/{id}). */
export type RegulatorMail = {
  id: string;
  messageId?: string;
  from: string;
  to: string;
  subject: string;
  receivedAt: string;
  text: string;
  attachments: { name: string; url: string }[];
  orderId: string | null;
  orderNumber: string | null;
  submissionId: string | null;
  matchedBy: 'tag' | 'reference' | 'none';
  processedAt: string;
};

// ---------------------------------------------------------------------------------------------
// PORTAL adapter (plan §6.4). Jobs live in portalJobs/{id}; the worker in worker/portal-runner
// claims them. The app never drives a browser itself.
// ---------------------------------------------------------------------------------------------

export type PortalJobStatus =
  | 'queued'        // created by an approved portal_stage proposal
  | 'running'       // worker has claimed it
  | 'otp_required'  // paused; waiting for otpResponse
  | 'staged'        // filled to the last click; waiting for decision 'submit' | 'abandon'
  | 'submitting'
  | 'submitted'     // done; result.reference set
  | 'handoff'       // driver could not complete (selector changed, captcha); prepared sheet attached
  | 'failed'
  | 'abandoned'
  | 'expired';

export type PortalJob = {
  id: string;
  orderId: string;
  orderNumber: string;
  serviceId: string;
  stepId: string;
  portalId: string;
  procedure: string;
  mode: 'stage' | 'auto';
  input: Record<string, any>;
  credentials: { label: string; encryptedValue: string }[];
  status: PortalJobStatus;
  createdAt: string;
  createdBy: string;
  claimedAt?: string;
  claimedBy?: string;      // worker instance id
  heartbeatAt?: string;
  /** Written by the worker when the portal asks for a PIN. */
  otpRequest?: { requestedAt: string; sentTo?: string; expiresAt: string };
  /** Written by the app when Kevin supplies the PIN. Cleared by the worker after use. */
  otpResponse?: { code: string; providedAt: string; providedBy: string };
  /** Written by the worker at stage time. */
  staged?: { at: string; screenshots: { label: string; url: string }[]; reviewSheet: { label: string; value: string }[]; expiresAt: string };
  /** Written by the app when Kevin decides. */
  decision?: { action: 'submit' | 'abandon'; at: string; by: string };
  result?: { reference?: string; confirmationUrl?: string; screenshots: { label: string; url: string }[]; notes: string[] };
  handoff?: { reason: string; sheet: { label: string; value: string }[]; screenshots: { label: string; url: string }[] };
  error?: string;
  log: { at: string; message: string }[];
};

export type PortalHealth = {
  portalId: string;
  checkedAt: string;
  ok: boolean;
  message: string;
  screenshotUrl?: string;
};

export const OTP_TIMEOUT_MINUTES = 10;
export const STAGE_TIMEOUT_MINUTES = 240;
